package leakednamespace

import (
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"testing"

	"golang.org/x/tools/go/analysis"
)

func TestAnalyzer_ReportsRepeatedSuffix(t *testing.T) {
	diagnostics := analyzeNames(t, map[string]string{
		"foo_wire.go": "package sample\n",
		"bar_wire.go": "package sample\n",
	})
	if len(diagnostics) != 1 || diagnostics[0].Message != "files [bar_wire.go, foo_wire.go] repeat suffix \"wire\"; consider a wire directory" {
		t.Fatalf("expected one wire suffix finding, got %#v", diagnostics)
	}
}

func TestFindClusters_RepeatedPrefixReportsDirectory(t *testing.T) {
	dir := t.TempDir()
	for _, name := range []string{"foo_bar.go", "foo_baz.go"} {
		if err := os.WriteFile(filepath.Join(dir, name), []byte("package sample\n"), 0o600); err != nil {
			t.Fatal(err)
		}
	}

	findings, err := findClusters(dir)
	if err != nil {
		t.Fatal(err)
	}
	if len(findings) != 1 || findings[0].token != "foo" || findings[0].direction != "prefix" {
		t.Fatalf("expected one foo prefix finding, got %#v", findings)
	}
}

func TestFindClusters_TestAndGeneratedFilesDoNotFormCluster(t *testing.T) {
	dir := t.TempDir()
	for name, body := range map[string]string{
		"foo_wire.go":      "package sample\n",
		"bar_wire_test.go": "package sample\n",
		"baz_wire.go":      "// Code generated by sample. DO NOT EDIT.\npackage sample\n",
	} {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(body), 0o600); err != nil {
			t.Fatal(err)
		}
	}

	findings, err := findClusters(dir)
	if err != nil {
		t.Fatal(err)
	}
	if len(findings) != 0 {
		t.Fatalf("expected no findings, got %#v", findings)
	}
}

func TestFindClusters_ExistingPrefixDirectorySuppressesFinding(t *testing.T) {
	dir := t.TempDir()
	for _, name := range []string{"foo_bar.go", "foo_baz.go"} {
		if err := os.WriteFile(filepath.Join(dir, name), []byte("package sample\n"), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	if err := os.Mkdir(filepath.Join(dir, "foo"), 0o700); err != nil {
		t.Fatal(err)
	}

	findings, err := findClusters(dir)
	if err != nil {
		t.Fatal(err)
	}
	if len(findings) != 0 {
		t.Fatalf("expected no findings, got %#v", findings)
	}
}

func analyzeNames(t *testing.T, sources map[string]string) []analysis.Diagnostic {
	t.Helper()
	dir := t.TempDir()
	fileSet := token.NewFileSet()
	files := make([]*ast.File, 0, len(sources))
	for name, source := range sources {
		path := filepath.Join(dir, name)
		if err := os.WriteFile(path, []byte(source), 0o600); err != nil {
			t.Fatal(err)
		}
		file, err := parser.ParseFile(fileSet, path, source, parser.ParseComments)
		if err != nil {
			t.Fatal(err)
		}
		files = append(files, file)
	}
	plugin, err := New(nil)
	if err != nil {
		t.Fatal(err)
	}
	analyzers, err := plugin.BuildAnalyzers()
	if err != nil {
		t.Fatal(err)
	}
	var diagnostics []analysis.Diagnostic
	pass := &analysis.Pass{
		Analyzer: analyzers[0],
		Fset:     fileSet,
		Files:    files,
		Report:   func(d analysis.Diagnostic) { diagnostics = append(diagnostics, d) },
	}
	if _, err := analyzers[0].Run(pass); err != nil {
		t.Fatal(err)
	}
	return diagnostics
}
