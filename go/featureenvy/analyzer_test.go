var fixtureSettings = map[string]any{"module": "fixture"}

func TestAnalyzer_ReportsFieldReadsWhateverTheName(t *testing.T) {
	source := `package fixture
type Account struct { Balance int }
func balanceOfAccount(a Account) int { return a.Balance }
func balanceForAccount(a Account) int { return a.Balance }
func balanceOf(a Account) int { return a.Balance }
func balanceFor(a Account) int { return a.Balance }
func balance(a Account) int { return a.Balance }
`
	got := analyzeSource(t, "sample.go", source)
	if len(got) != 5 {
		t.Fatalf("diagnostics: got %d, want 5", len(got))
	}
}

