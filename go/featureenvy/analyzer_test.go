var fixtureSettings = map[string]any{"module": "fixture"}

func TestAnalyzer_ReportsFieldReadsWhateverTheName(t *testing.T) {
	source := `package fixture
type Account struct { Balance int }
func balanceOfAccount(a Account) int { return a.Balance }
func balanceForAccount(a Account) int { return a.Balance }
func balanceOf(a Account) int { return a.Balance }
func balanceFor(a Account) int { return a.Balance }
func balance(a Account) int { return a.Balance }
`
	got := analyzeSource(t, "sample.go", source)
	if len(got) != 5 {
		t.Fatalf("diagnostics: got %d, want 5", len(got))
	}
}

func TestAnalyzer_ReportsMethodCallReads(t *testing.T) {
	source := `package fixture
type Account struct { Balance int }
func (a Account) Status() int { return a.Balance }
func statusOfAccount(a Account) int { return a.Status() }
`
	if got := analyzeSource(t, "sample.go", source); len(got) != 1 {
		t.Fatalf("diagnostics: got %d, want 1", len(got))
	}
}

func TestAnalyzer_SkipsMethodsAndWrites(t *testing.T) {
	source := `package fixture
type Account struct { Balance int }
func (a Account) balanceOfAccount() int { return a.Balance }
func updateForAccount(a *Account) { a.Balance = 1 }
`
	if got := analyzeSource(t, "sample.go", source); len(got) != 0 {
		t.Fatalf("diagnostics: got %d, want none", len(got))
	}
}

