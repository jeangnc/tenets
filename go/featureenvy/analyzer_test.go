func TestAnalyzer_ReportsOnlyFunctionsWhoseArgumentCouldOwnTheRead(t *testing.T) {
	plugin, err := New(map[string]any{"module": "example.com/app", "foreign": []string{"example.com/app/vendorapi"}})
	if err != nil {
		t.Fatal(err)
	}
	analyzers, err := plugin.BuildAnalyzers()
	if err != nil {
		t.Fatal(err)
	}
	analysistest.Run(t, analysistest.TestData(), analyzers[0], "example.com/app/app")
}

func analyzeSource(t *testing.T, filename, source string) []analysis.Diagnostic {
	t.Helper()
	fileSet := token.NewFileSet()
	file, err := parser.ParseFile(fileSet, filename, source, parser.ParseComments)
	if err != nil {
		t.Fatal(err)
	}
	info := &types.Info{
		Defs:       make(map[*ast.Ident]types.Object),
		Uses:       make(map[*ast.Ident]types.Object),
		Selections: make(map[*ast.SelectorExpr]*types.Selection),
	}
	config := types.Config{Importer: importer.Default()}
	pkg, err := config.Check("fixture", fileSet, []*ast.File{file}, info)
	if err != nil {
		t.Fatal(err)
	}
	plugin, err := New(fixtureSettings)
	if err != nil {
		t.Fatal(err)
	}
	analyzers, err := plugin.BuildAnalyzers()
	if err != nil {
		t.Fatal(err)
	}
	var diagnostics []analysis.Diagnostic
	pass := &analysis.Pass{
		Analyzer:  analyzers[0],
		Fset:      fileSet,
		Files:     []*ast.File{file},
		Pkg:       pkg,
		TypesInfo: info,
		Report:    func(d analysis.Diagnostic) { diagnostics = append(diagnostics, d) },
	}
	if _, err := analyzers[0].Run(pass); err != nil {
		t.Fatal(err)
	}
	return diagnostics
}
